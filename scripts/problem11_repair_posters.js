/**
 * PRAFLIX — Problem 11 Poster Repair Script
 * 
 * Strategy:
 * 1. If poster = local path AND file exists on disk → keep (valid_local)
 * 2. If poster = local path BUT file missing on disk:
 *    a. If sourcePosterUrl is TMDb image → use TMDb URL (valid_remote)
 *    b. Otherwise → use fallback.svg
 * 3. If poster = remote URL already → keep (valid_remote)  
 * 4. If poster = fallback.svg:
 *    a. If sourcePosterUrl is TMDb image → promote to TMDb URL (valid_remote)
 *    b. Otherwise → keep fallback.svg
 * 5. Known mismatch IDs → force to fallback.svg
 */

const fs = require('fs');
const path = require('path');

const CATALOG_PATH = 'data/catalog.json';
const POSTER_VALID_IDS_PATH = 'data/poster-valid-ids.js';
const FALLBACK = 'assets/posters/fallback.svg';

// Known mismatched posters (different title sharing wrong poster)
const KNOWN_MISMATCHES = new Set([
  6808,  // Kaashmora 2 incorrectly sharing Aayirathil Oruvan poster
  7302,  // Hyper incorrectly sharing Eedo Rakam Aado Rakam poster
]);

const cat = JSON.parse(fs.readFileSync(CATALOG_PATH, 'utf8'));
const originalCount = cat.length;

const auditRows = [];
let repairedCount = 0;
const validIds = [];

cat.forEach(item => {
  const id = item.canonicalId;
  const oldPoster = item.poster || '';
  let newPoster = oldPoster;
  let status = 'unchanged';

  // Check known mismatches first
  if (KNOWN_MISMATCHES.has(id)) {
    newPoster = FALLBACK;
    status = 'repaired_mismatch_to_fallback';
    repairedCount++;
  }
  // Local file path
  else if (oldPoster.startsWith('assets/posters/') && oldPoster !== FALLBACK) {
    const diskPath = path.join(__dirname, '..', oldPoster);
    if (fs.existsSync(diskPath) && fs.statSync(diskPath).size > 100) {
      // Valid local file — keep
      status = 'valid_local';
      validIds.push(id);
    } else {
      // File missing from disk
      if (item.sourcePosterUrl && item.sourcePosterUrl.startsWith('https://image.tmdb.org/t/p/')) {
        newPoster = item.sourcePosterUrl;
        status = 'repaired_missing_local_to_tmdb';
        repairedCount++;
        validIds.push(id);
      } else {
        newPoster = FALLBACK;
        status = 'repaired_missing_local_to_fallback';
        repairedCount++;
      }
    }
  }
  // Already a remote URL
  else if (oldPoster.startsWith('http://') || oldPoster.startsWith('https://')) {
    status = 'valid_remote';
    validIds.push(id);
  }
  // Currently fallback SVG
  else if (oldPoster === FALLBACK) {
    // Promote to TMDb if available
    if (item.sourcePosterUrl && item.sourcePosterUrl.startsWith('https://image.tmdb.org/t/p/')) {
      newPoster = item.sourcePosterUrl;
      status = 'promoted_fallback_to_tmdb';
      repairedCount++;
      validIds.push(id);
    } else {
      status = 'valid_fallback';
    }
  }
  // Empty or null
  else {
    newPoster = FALLBACK;
    status = 'repaired_empty_to_fallback';
    repairedCount++;
  }

  item.poster = newPoster;
  auditRows.push({ canonicalId: id, title: item.displayTitle, year: item.year, oldPoster, newPoster, status });
});

// Write repaired catalog
fs.writeFileSync(CATALOG_PATH, JSON.stringify(cat), 'utf8');
console.log(`✓ Saved repaired catalog: ${cat.length} records`);

// Regenerate poster-valid-ids.js
const validSet = JSON.stringify(validIds);
const orderedArr = JSON.stringify(validIds);
const posterJs = `/* PRAFLIX Poster Validity Index — regenerated by Problem 11 repair */
/* Valid: ${validIds.length} | Total: ${cat.length} */
window.PRAFLIX_POSTER_VALID_IDS = new Set(${validSet});
window.PRAFLIX_POSTER_ORDERED_IDS = ${orderedArr};
`;
fs.writeFileSync(POSTER_VALID_IDS_PATH, posterJs, 'utf8');
console.log(`✓ Regenerated poster-valid-ids.js: ${validIds.length} valid IDs`);

// Write audit JSON
const statusCounts = {};
auditRows.forEach(r => {
  statusCounts[r.status] = (statusCounts[r.status] || 0) + 1;
});

const posterAudit = {
  generated: new Date().toISOString(),
  totalRecords: originalCount,
  validLocalPosters: statusCounts['valid_local'] || 0,
  validRemotePosters: (statusCounts['valid_remote'] || 0) + (statusCounts['repaired_missing_local_to_tmdb'] || 0) + (statusCounts['promoted_fallback_to_tmdb'] || 0),
  fallbackPosters: (statusCounts['valid_fallback'] || 0) + (statusCounts['repaired_missing_local_to_fallback'] || 0) + (statusCounts['repaired_mismatch_to_fallback'] || 0) + (statusCounts['repaired_empty_to_fallback'] || 0),
  totalRepaired: repairedCount,
  statusBreakdown: statusCounts,
  totalValidInIndex: validIds.length,
  knownMismatchesFixed: KNOWN_MISMATCHES.size
};

fs.writeFileSync('data/problem11_poster_audit.json', JSON.stringify(posterAudit, null, 2), 'utf8');
console.log('\n=== POSTER REPAIR SUMMARY ===');
console.log('Total records:', posterAudit.totalRecords);
console.log('Valid local on-disk:', posterAudit.validLocalPosters);
console.log('Valid remote (TMDb/http):', posterAudit.validRemotePosters);
console.log('Fallback SVG:', posterAudit.fallbackPosters);
console.log('Total repaired:', posterAudit.totalRepaired);
console.log('Status breakdown:', JSON.stringify(statusCounts, null, 2));
console.log('Valid IDs in index:', posterAudit.totalValidInIndex);
console.log('\n✓ Saved data/problem11_poster_audit.json');
